SELECT cmp_ok(
    (SELECT least(
        (SELECT count(*) FROM user_roles), (SELECT count(*) FROM role_permissions),
        (SELECT count(*) FROM user_permissions), (SELECT count(*) FROM roles),
        (SELECT count(*) FROM permissions), (SELECT count(*) FROM permission_hierarchy))),
