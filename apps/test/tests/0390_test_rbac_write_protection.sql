-- A non-admin cannot write the users table or the RBAC tables.
--
-- Each part sets up its own fixtures; a part after the first starts by
-- restoring the connection's role and the runner's search_path. Parts:
--   1. users table write protection
--   2. No escalation through the RBAC tables
--   3. The deny-all tables (_settings, _apikeys)
--   4. UPDATE and DELETE on the RBAC and catalog tables
--   5. external_id of an existing user is written by an administrator only
BEGIN;

SELECT plan(57);

-- =====================================================
-- PART 1: users table write protection
-- =====================================================
-- Verify that a regular (non-admin) user cannot write the users table directly.
--
-- Only admins (the `user:manage` permission) may INSERT/UPDATE/DELETE users via
-- RLS (the policies create_entity_policies in 0160_dd_functions.sql generates
-- from users.edit_permission). First-login provisioning happens through the
-- SECURITY DEFINER rbac.upsert_user_from_jwt(), which bypasses RLS but only ever
-- touches the caller's OWN row. A regular user must NOT be able to change any
-- user row (their own or someone else's) by writing the table directly.

-- user1 is a regular user (no user:manage).
SELECT authenticate_as('user1');

-- 1. INSERT is rejected by the RLS WITH CHECK (insufficient_privilege).
SELECT throws_ok(
    $$ INSERT INTO users (external_id, email) VALUES ('attacker_injected', 'evil@example.com') $$,
    '42501',
    NULL,
    'regular user cannot INSERT into users (RLS WITH CHECK)'
);

-- 2. UPDATE of another user's email is a silent no-op: RLS USING hides the row,
--    so zero rows are affected (and nothing changes).
WITH upd AS (
    UPDATE users SET email = 'hacked@evil.com' WHERE external_id = 'user2' RETURNING 1
)
SELECT is( count(*)::int, 0,
    'regular user UPDATE of another user affects 0 rows' ) FROM upd;

-- 3. DELETE is likewise a no-op for a regular user.
WITH del AS (
    DELETE FROM users WHERE external_id = 'user2' RETURNING 1
)
SELECT is( count(*)::int, 0,
    'regular user DELETE on users affects 0 rows' ) FROM del;

-- 4. Confirm (as an admin) the attacked row was untouched.
SELECT authenticate_as('user3');  -- admin: has user:manage / user:read
SELECT isnt(
    (SELECT email FROM users WHERE external_id = 'user2'),
    'hacked@evil.com',
    'user2 email is unchanged after the regular-user write attempts'
);

-- 5. Positive control: an admin CAN update users.
WITH upd AS (
    UPDATE users SET email = email WHERE external_id = 'user2' RETURNING 1
)
SELECT is( count(*)::int, 1,
    'admin (user:manage) can UPDATE users' ) FROM upd;

-- =====================================================
-- PART 2: No escalation through the RBAC tables
-- =====================================================
-- Test (PIN, expected GREEN): a non-admin cannot escalate by writing the RBAC tables.
--
-- The stage-2 panel checked these and found them correctly forbidden (the RBAC tables are
-- admin-gated via RLS WITH CHECK, generated by create_entity_policies in
-- 0160_dd_functions.sql), but UNTESTED — so this pins invariant
-- I5 (no privilege escalation) against regression. Unlike 0610/0620 these should PASS now.
--
-- Fixtures: user1=1001 (plain user, holds the User role = role 1), user3=admin.

RESET ROLE;
SET LOCAL search_path TO public, pgtap;

-- Stash valid keys as admin so each attempt below fails ONLY on RLS (42501), not on a bad FK.
-- The permission key is its name, so that one is a literal.
SELECT authenticate_as('user3');
CREATE TEMP TABLE _esc AS
SELECT
    (SELECT id FROM roles       WHERE role_name       = 'Administrator') AS admin_role,
    (SELECT id FROM roles       WHERE role_name       = 'User')          AS user_role,
    'admin'::text                                                        AS admin_perm;

-- =====================================================
-- As user1 (non-admin): every self-grant path must be rejected by RLS (42501).
-- =====================================================
SELECT authenticate_as('user1');

-- 1. Self-assign the Administrator role via user_roles.
SELECT throws_ok(
    $$ INSERT INTO user_roles (user_id, role_id)
       VALUES (1001, (SELECT admin_role FROM _esc)) $$,
    '42501', NULL,
    'I5: user1 cannot self-grant Administrator via user_roles'
);

-- 2. Self-grant the admin permission directly via user_permissions.
SELECT throws_ok(
    $$ INSERT INTO user_permissions (user_id, permission_name)
       VALUES (1001, (SELECT admin_perm FROM _esc)) $$,
    '42501', NULL,
    'I5: user1 cannot self-grant the admin permission via user_permissions'
);

-- 3. Grant the admin permission to the User role (which user1 holds) via role_permissions.
SELECT throws_ok(
    $$ INSERT INTO role_permissions (role_id, permission_name)
       VALUES ((SELECT user_role FROM _esc), (SELECT admin_perm FROM _esc)) $$,
    '42501', NULL,
    'I5: user1 cannot grant admin to the User role via role_permissions'
);

-- 4. Insert a brand-new permission (which would auto-grant to Administrator).
SELECT throws_ok(
    $$ INSERT INTO permissions (permission_name, description, module_id)
       VALUES ('evil:escalate', 'should be rejected', 1) $$,
    '42501', NULL,
    'I5: user1 cannot create a permission'
);

-- =====================================================
-- PART 3: the deny-all tables
-- =====================================================
-- _settings and _apikeys carry one policy, FOR ALL, with USING and WITH CHECK
-- both false, and nobody is exempt: the request role is refused whatever the
-- caller holds, an administrator included. Reading yields no row, an INSERT is
-- refused by the policy (42501), and UPDATE and DELETE find nothing to change.
-- "Nothing changed" is proved against the owner's view of the tables, taken
-- before the attempts, and both tables hold a real row so an empty table
-- cannot satisfy it by itself.
--
-- Helpers, all in pg_temp. write_effect runs one UPDATE and one DELETE over the
-- whole table as the calling role and reports the rows each changed, or the
-- SQLSTATE if a statement raised, so a refusal where silence is expected shows
-- up in the assertion and does not abort the file. digest_snapshot holds a hash
-- of every table's rows; changed_tables names those whose rows differ from it.

RESET ROLE;
SET LOCAL search_path TO public, pgtap;

CREATE FUNCTION pg_temp.write_effect(p_table TEXT, p_set TEXT) RETURNS TEXT AS $$
DECLARE
    v_updated BIGINT;
    v_deleted BIGINT;
BEGIN
    EXECUTE format('UPDATE %I SET %s', p_table, p_set);
    GET DIAGNOSTICS v_updated = ROW_COUNT;
    EXECUTE format('DELETE FROM %I', p_table);
    GET DIAGNOSTICS v_deleted = ROW_COUNT;
    RETURN format('update %s, delete %s', v_updated, v_deleted);
EXCEPTION WHEN OTHERS THEN
    RETURN 'raised ' || SQLSTATE;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION pg_temp.table_digest(p_table TEXT) RETURNS TEXT AS $$
DECLARE
    v_digest TEXT;
BEGIN
    EXECUTE format(
        'SELECT md5(coalesce(string_agg(to_jsonb(t)::text, ''|'' ORDER BY to_jsonb(t)::text), '''')) FROM %I t',
        p_table) INTO v_digest;
    RETURN v_digest;
END;
$$ LANGUAGE plpgsql;

-- A direct per-user grant, so user_permissions is not an empty table.
INSERT INTO user_permissions (user_id, permission_name, granted_by)
SELECT u1.id, 'public:read', u3.id
FROM users u1, users u3
WHERE u1.external_id = 'user1' AND u3.external_id = 'user3';

CREATE TEMP TABLE digest_snapshot AS
SELECT t.name AS tbl, pg_temp.table_digest(t.name) AS digest
FROM unnest(ARRAY['_settings', '_apikeys', 'user_roles', 'role_permissions',
                  'user_permissions', 'roles', 'permissions',
                  'permission_hierarchy', 'entities']) AS t(name);

CREATE FUNCTION pg_temp.changed_tables() RETURNS TEXT AS $$
    SELECT string_agg(d.tbl, ', ' ORDER BY d.tbl)
    FROM digest_snapshot d
    WHERE pg_temp.table_digest(d.tbl) <> d.digest;
$$ LANGUAGE sql;

SELECT is(
    (SELECT string_agg(t.name, ', ' ORDER BY t.name)
     FROM unnest(ARRAY['_settings', '_apikeys', 'user_roles', 'role_permissions',
                       'user_permissions', 'roles', 'permissions',
                       'permission_hierarchy', 'entities']) AS t(name)
     WHERE pg_temp.table_digest(t.name) = md5('')),
    NULL::text,
    'setup: every table attacked below holds at least one row'
);

-- As user1, a plain user.
SELECT authenticate_as('user1');

SELECT is((SELECT count(*)::int FROM _settings), 0,
    'user1 reads no row of _settings');
SELECT throws_ok(
    $$ INSERT INTO _settings (name, value) VALUES ('probe_setting', 'x') $$,
    '42501', NULL,
    'user1 cannot INSERT into _settings');
SELECT is(pg_temp.write_effect('_settings', $$value = 'tampered'$$), 'update 0, delete 0',
    'user1 UPDATE and DELETE on _settings change no row');

SELECT is((SELECT count(*)::int FROM _apikeys), 0,
    'user1 reads no row of _apikeys');
SELECT throws_ok(
    $$ INSERT INTO _apikeys (user_id, key_id, secret_hash)
       VALUES ((SELECT id FROM users WHERE external_id = 'user1'), 'uk-probe00000001', 'x') $$,
    '42501', NULL,
    'user1 cannot INSERT into _apikeys');
SELECT is(pg_temp.write_effect('_apikeys', $$description = 'tampered'$$), 'update 0, delete 0',
    'user1 UPDATE and DELETE on _apikeys change no row');

RESET ROLE;
SELECT is(pg_temp.changed_tables(), NULL,
    'after the attempts of user1 the owner finds _settings and _apikeys as they were');

-- As user3, the administrator: nothing in the policy names a permission.
SELECT authenticate_as('user3');

SELECT is((SELECT count(*)::int FROM _settings), 0,
    'user3 reads no row of _settings');
SELECT throws_ok(
    $$ INSERT INTO _settings (name, value) VALUES ('probe_setting', 'x') $$,
    '42501', NULL,
    'user3 cannot INSERT into _settings');
SELECT is(pg_temp.write_effect('_settings', $$value = 'tampered'$$), 'update 0, delete 0',
    'user3 UPDATE and DELETE on _settings change no row');

SELECT is((SELECT count(*)::int FROM _apikeys), 0,
    'user3 reads no row of _apikeys');
SELECT throws_ok(
    $$ INSERT INTO _apikeys (user_id, key_id, secret_hash)
       VALUES ((SELECT id FROM users WHERE external_id = 'user3'), 'uk-probe00000002', 'x') $$,
    '42501', NULL,
    'user3 cannot INSERT into _apikeys');
SELECT is(pg_temp.write_effect('_apikeys', $$description = 'tampered'$$), 'update 0, delete 0',
    'user3 UPDATE and DELETE on _apikeys change no row');

RESET ROLE;
SELECT is(pg_temp.changed_tables(), NULL,
    'after the attempts of user3 the owner finds _settings and _apikeys as they were');

-- =====================================================
-- PART 4: the RBAC and catalog tables
-- =====================================================
-- Every policy on these tables names admin for its write side, so neither
-- user1 (the User role) nor user2 (Northwind Sales) changes a row. entities is
