export class CoverageCollector {
  private client: Client;
  private opts: CoverageOptions;
  private before: StatsSnapshot = { functions: new Map(), tables: new Map() };
  caps: CoverageCapabilities = {
    serverVersion: "",
    user: "",
    superuser: false,
    plpgsqlCheck: { available: false },
    trackFunctions: { enabled: false },
    universe: { mode: "schemas", schemas: CORE_SCHEMAS },
  };

  constructor(client: Client, opts: CoverageOptions) {
    this.client = client;
    this.opts = opts;
  }

  private log(line: string): void {
    console.log(this.opts.tap ? `# ${line}` : line);
  }

  private warn(line: string): void {
    console.warn(this.opts.tap ? `# ${line}` : line);
  }

  private async rows<T>(sql: string): Promise<T[]> {
    const result = await this.client.queryObject<T>(sql);
    return result.rows;
  }

  private get ext(): string {
    return quoteIdent(this.caps.plpgsqlCheck.schema ?? "extensions");
  }

  /**
   * Prepares the session. Every step is its own statement so that a failure
   * (no extension, no superuser) degrades that one capability instead of the
   * whole run. Runs once, before the first test file, on the test connection.
   */
  async preflight(): Promise<CoverageCapabilities> {
    const [id] = await this.rows<
      { version: string; user: string; superuser: boolean }
    >(
      `SELECT pg_catalog.version() AS version, current_user::text AS "user",
              pg_catalog.current_setting('is_superuser') = 'on' AS superuser`,
    );
    this.caps.serverVersion = id.version;
    this.caps.user = id.user;
    this.caps.superuser = id.superuser;

    // plpgsql_check: available? install into `extensions` (skipped by dropall
    // and by the 0240 guard test), then resolve where it actually lives.
    const avail = await this.rows<
      { installed_version: string | null; default_version: string }
    >(
      `SELECT installed_version, default_version
         FROM pg_catalog.pg_available_extensions WHERE name = 'plpgsql_check'`,
    );
    if (avail.length === 0) {
      this.caps.plpgsqlCheck = {
        available: false,
        reason:
          "plpgsql_check is not available on this server (statement coverage disabled)",
      };
    } else {
      try {
        if (!avail[0].installed_version) {
          await this.client.queryArray(
            `CREATE SCHEMA IF NOT EXISTS extensions`,
          );
          await this.client.queryArray(
            `CREATE EXTENSION IF NOT EXISTS plpgsql_check WITH SCHEMA extensions`,
          );
        }
        const [ext] = await this.rows<{ schema: string; version: string }>(
          `SELECT n.nspname AS schema, e.extversion AS version
             FROM pg_catalog.pg_extension e
             JOIN pg_catalog.pg_namespace n ON n.oid = e.extnamespace
            WHERE e.extname = 'plpgsql_check'`,
        );
        this.caps.plpgsqlCheck = {
          available: true,
          schema: ext.schema,
          version: ext.version,
        };
        if (ext.schema !== "extensions") {
          this.warn(
            `plpgsql_check is installed in schema "${ext.schema}"; deno task dropall only skips the "extensions" schema`,
          );
        }
        // Calling into the extension loads its library into this session and
        // installs the PL/pgSQL plugin hooks; also proves EXECUTE privilege.
        await this.client.queryArray(
          `SELECT ${this.ext}.plpgsql_profiler_reset_all()`,
        );
        await this.client.queryArray(`SET plpgsql_check.profiler = on`);
        await this.client.queryArray(`SET plpgsql_check.use_lxcache = off`);
      } catch (error) {
        this.caps.plpgsqlCheck = {
          available: false,
          reason: `plpgsql_check could not be enabled: ${errorMessage(error)}`,
        };
      }
    }

    // Function call counters for every language (superuser-only GUC).
    try {
      await this.client.queryArray(`SET track_functions = 'all'`);
      this.caps.trackFunctions = { enabled: true };
    } catch (error) {
      this.caps.trackFunctions = {
        enabled: false,
        reason: `cannot SET track_functions (${
          errorMessage(error)
        }); SQL-language functions are not measurable`,
      };
    }

    // Always the schema universe. It used to switch to extension membership
    // when pg_semantius was installed, but the extension is now a THIN
    // INSTALLER: its only members are the `semantius` schema and a handful of
    // installer functions, so the membership universe would report ~4 objects
    // and miss every core function the suite actually exercises. Both install
    // layouts produce the same ordinary objects in the same five schemas.
    this.caps.universe = { mode: "schemas", schemas: CORE_SCHEMAS };

    const parts: string[] = [];
    parts.push(
      this.caps.plpgsqlCheck.available
        ? `plpgsql_check ${this.caps.plpgsqlCheck.version} (schema ${this.caps.plpgsqlCheck.schema})`
        : "plpgsql_check unavailable",
    );
    parts.push(
      this.caps.trackFunctions.enabled
        ? "track_functions on"
        : "track_functions off",
    );
    parts.push(
      this.caps.universe.mode === "extension"
        ? "universe: extension pg_semantius"
        : `universe: schemas ${CORE_SCHEMAS.join(",")}`,
    );
    this.log(`Coverage: ${parts.join("; ")}`);
    if (!this.caps.plpgsqlCheck.available && this.caps.plpgsqlCheck.reason) {
      this.warn(`Coverage: ${this.caps.plpgsqlCheck.reason}`);
    }
    if (!this.caps.trackFunctions.enabled && this.caps.trackFunctions.reason) {
      this.warn(`Coverage: ${this.caps.trackFunctions.reason}`);
    }
    if (
      !this.caps.plpgsqlCheck.available && !this.caps.trackFunctions.enabled
    ) {
      this.warn(
        "Coverage: neither the profiler nor function statistics are available; nothing can be measured on this connection",
      );
    }
    return this.caps;
  }

  private async snapshot(): Promise<StatsSnapshot> {
    const functions = new Map<number, number>();
    for (
      const r of await this.rows<{ oid: unknown; calls: unknown }>(
        `SELECT funcid::bigint AS oid, calls::bigint AS calls
           FROM pg_catalog.pg_stat_user_functions`,
      )
    ) {
      functions.set(num(r.oid), num(r.calls));
    }
    const tables = new Map<number, TableStats>();
    for (
      const r of await this.rows<
        {
          oid: unknown;
          seq: unknown;
          idx: unknown;
          ins: unknown;
          upd: unknown;
          del: unknown;
        }
      >(
        `SELECT relid::bigint AS oid,
                COALESCE(seq_scan, 0)::bigint AS seq, COALESCE(idx_scan, 0)::bigint AS idx,
                COALESCE(n_tup_ins, 0)::bigint AS ins, COALESCE(n_tup_upd, 0)::bigint AS upd,
                COALESCE(n_tup_del, 0)::bigint AS del
           FROM pg_catalog.pg_stat_user_tables`,
      )
    ) {
      tables.set(num(r.oid), {
        seq: num(r.seq),
        idx: num(r.idx),
        ins: num(r.ins),
        upd: num(r.upd),
        del: num(r.del),
      });
    }
    return { functions, tables };
  }

  /** Records the counters before the first test file runs. */
  async snapshotBefore(): Promise<void> {
    this.before = await this.snapshot();
  }

  private universeFunctionsSql(): string {
    const base = `
      SELECT p.oid::bigint AS oid, n.nspname AS schema, p.proname AS name,
             pg_catalog.pg_get_function_identity_arguments(p.oid) AS args,
             l.lanname AS language, p.prokind::text AS prokind, p.prosecdef,
             (p.prorettype IN ('pg_catalog.trigger'::pg_catalog.regtype,
                               'pg_catalog.event_trigger'::pg_catalog.regtype)) AS is_trigger,
             p.prosrc
        FROM pg_catalog.pg_proc p
        JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
        JOIN pg_catalog.pg_language l ON l.oid = p.prolang
       WHERE l.lanname IN ('plpgsql', 'sql')`;
    const generated = `(n.nspname = 'public' AND (
             p.proname = '_label'
          OR (p.proname LIKE '%\\_label' AND pg_catalog.pg_get_function_identity_arguments(p.oid) LIKE 'rec %')
          OR p.proname LIKE 'compute\\_validate\\_%'
          OR p.proname LIKE 'select\\_rule\\_%'))`;
    const anyExtensionMember = `EXISTS (
          SELECT 1 FROM pg_catalog.pg_depend d
           WHERE d.classid = 'pg_catalog.pg_proc'::pg_catalog.regclass AND d.objid = p.oid
             AND d.deptype = 'e')`;
    if (this.caps.universe.mode === "extension") {
      const member = `EXISTS (
          SELECT 1 FROM pg_catalog.pg_depend d
            JOIN pg_catalog.pg_extension e ON e.oid = d.refobjid
           WHERE d.classid = 'pg_catalog.pg_proc'::pg_catalog.regclass AND d.objid = p.oid
             AND d.refclassid = 'pg_catalog.pg_extension'::pg_catalog.regclass
             AND d.deptype = 'e' AND e.extname = '${this.caps.universe.extension}')`;
      return `${base}
         AND (${member}
              OR (${generated} AND NOT ${anyExtensionMember}))
       ORDER BY 2, 3, 4`;
    }
    const schemas = CORE_SCHEMAS.map((s) => `'${s}'`).join(", ");
    const helpers = TEST_HELPERS.map((s) => `'${s}'`).join(", ");
    return `${base}
         AND n.nspname IN (${schemas})
         AND p.proname NOT IN (${helpers})
         AND NOT ${anyExtensionMember}
       ORDER BY 2, 3, 4`;
  }

  private universeTablesSql(): string {
    const base = `
      SELECT c.oid::bigint AS oid, n.nspname AS schema, c.relname AS name,
             (SELECT count(*) FROM pg_catalog.pg_policy pol WHERE pol.polrelid = c.oid)::bigint AS policies
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
       WHERE c.relkind IN ('r', 'p')`;
    if (this.caps.universe.mode === "extension") {
      return `${base}
         AND EXISTS (
          SELECT 1 FROM pg_catalog.pg_depend d
            JOIN pg_catalog.pg_extension e ON e.oid = d.refobjid
           WHERE d.classid = 'pg_catalog.pg_class'::pg_catalog.regclass AND d.objid = c.oid
             AND d.refclassid = 'pg_catalog.pg_extension'::pg_catalog.regclass
             AND d.deptype = 'e' AND e.extname = '${this.caps.universe.extension}')
       ORDER BY 2, 3`;
    }
    const schemas = CORE_SCHEMAS.map((s) => `'${s}'`).join(", ");
    return `${base}
         AND n.nspname IN (${schemas})
         AND NOT EXISTS (
          SELECT 1 FROM pg_catalog.pg_depend d
           WHERE d.classid = 'pg_catalog.pg_class'::pg_catalog.regclass AND d.objid = c.oid
             AND d.deptype = 'e')
       ORDER BY 2, 3`;
  }

  /**
   * Reads the counters and the profiler after the suite ran and turns them
   * into a summary. Must run on the same connection as the tests (the
   * profiler data is session-local unless plpgsql_check is preloaded).
   */
  async collect(
    run: CoverageSummary["run"],
    databaseUrl: string,
  ): Promise<CoverageSummary> {
    // Tests SET ROLE inside their rolled-back transactions; be defensive anyway.
    try {
      await this.client.queryArray(`RESET ROLE`);
    } catch {
      // ignore
    }
    // Counters are flushed to shared memory when the backend goes idle; force
    // the next flush and give it one more round trip so the after-snapshot
    // includes the last test file.
    try {
      await this.client.queryArray(
        `SELECT pg_catalog.pg_stat_force_next_flush()`,
      );
      await this.client.queryArray(`SELECT 1`);
    } catch {
      // pre-15 servers: the 1s flush interval usually has passed anyway
    }
    const after = await this.snapshot();

    const universe = (await this.rows<
      {
        oid: unknown;
        schema: string;
        name: string;
        args: string;
        language: string;
        prokind: string;
        prosecdef: boolean;
        is_trigger: boolean;
        prosrc: string;
      }
    >(this.universeFunctionsSql())).map((r): UniverseFunction => ({
      oid: num(r.oid),
      schema: r.schema,
      name: r.name,
      args: r.args,
      language: r.language,
      prokind: r.prokind,
      prosecdef: r.prosecdef,
      isTrigger: r.is_trigger,
      prosrc: r.prosrc,
    }));
    const tables = (await this.rows<
      { oid: unknown; schema: string; name: string; policies: unknown }
    >(this.universeTablesSql())).map((r): UniverseTable => ({
      oid: num(r.oid),
      schema: r.schema,
      name: r.name,
      policies: num(r.policies),
    }));

    const callsOf = (oid: number) =>
      (after.functions.get(oid) ?? 0) - (this.before.functions.get(oid) ?? 0);

    // Profiler data (session-local): exec counts, branch ratios, statements.
    const execCounts = new Map<number, number>();
    const branches = new Map<number, number>();
    const statements = new Map<number, { lineno: number; exec: number }[]>();
    const lineErrors = new Map<number, string>();
    if (this.caps.plpgsqlCheck.available) {
      for (
        const r of await this.rows<{ oid: unknown; exec_count: unknown }>(
          `SELECT f.funcoid::pg_catalog.oid::bigint AS oid, f.exec_count::bigint AS exec_count
             FROM ${this.ext}.plpgsql_profiler_functions_all() f`,
        )
      ) {
        execCounts.set(num(r.oid), num(r.exec_count));
      }
      const plpgsql = universe.filter((f) => f.language === "plpgsql");
      const called = plpgsql.filter((f) =>
        (execCounts.get(f.oid) ?? 0) > 0 || callsOf(f.oid) > 0
      );
      // Branch ratio only for executed functions (never-executed ones read 1.0).
      for (const chunk of chunks(called.map((f) => f.oid), 100)) {
        try {
          for (
            const r of await this.rows<{ oid: unknown; branch_pct: unknown }>(
              `SELECT p.oid::bigint AS oid,
                      ${this.ext}.plpgsql_coverage_branches(p.oid::pg_catalog.regprocedure) AS branch_pct
                 FROM pg_catalog.pg_proc p WHERE p.oid IN (${
                chunk.join(", ")
              })`,
            )
          ) {
            branches.set(num(r.oid), num(r.branch_pct) * 100);
          }
        } catch {
          for (const oid of chunk) {
            try {
              const [r] = await this.rows<{ branch_pct: unknown }>(
                `SELECT ${this.ext}.plpgsql_coverage_branches(${oid}::pg_catalog.oid::pg_catalog.regprocedure) AS branch_pct`,
              );
              branches.set(oid, num(r.branch_pct) * 100);
            } catch {
              // branch coverage is informational only
            }
          }
        }
      }
      // Per-statement rows for every PL/pgSQL function: never-executed ones
      // still yield one row per statement with exec_stmts 0/NULL.
      const statementsSql = (oids: number[]) =>
        `SELECT p.oid::bigint AS oid, s.lineno, COALESCE(s.exec_stmts, 0)::bigint AS exec_stmts
           FROM pg_catalog.pg_proc p
           CROSS JOIN LATERAL ${this.ext}.plpgsql_profiler_function_statements_tb(p.oid::pg_catalog.regprocedure) s
          WHERE p.oid IN (${oids.join(", ")})`;
      const addRows = (
        rows: { oid: unknown; lineno: unknown; exec_stmts: unknown }[],
      ) => {
        for (const r of rows) {
          const oid = num(r.oid);
          const list = statements.get(oid) ?? [];
          list.push({ lineno: num(r.lineno), exec: num(r.exec_stmts) });
          statements.set(oid, list);
        }
      };
      for (const chunk of chunks(plpgsql.map((f) => f.oid), 100)) {
        try {
          addRows(await this.rows(statementsSql(chunk)));
        } catch {
          for (const oid of chunk) {
            try {
              addRows(await this.rows(statementsSql([oid])));
            } catch (error) {
              lineErrors.set(oid, errorMessage(error));
            }
          }
        }
      }
    }

    const sourceIndex = await buildSourceIndex();
    const functions: FunctionCoverage[] = universe.map((f) => {
      const calls = this.caps.trackFunctions.enabled ? callsOf(f.oid) : null;
      const execCount =
        this.caps.plpgsqlCheck.available && f.language === "plpgsql"
          ? (execCounts.get(f.oid) ?? 0)
          : null;
      let called: boolean | null;
      if (calls === null && execCount === null) called = null;
      else called = (calls ?? 0) > 0 || (execCount ?? 0) > 0;

      const source = locateFunction(sourceIndex, f);
      const stmtRows = statements.get(f.oid);
      let stmts: FunctionCoverage["statements"] = null;
      let lineHits: [number, number][] | null = null;
      const uncovered: number[] = [];
      if (stmtRows && stmtRows.length > 0) {
        const executed = stmtRows.filter((s) => s.exec > 0).length;
        stmts = {
          total: stmtRows.length,
          executed,
          pct: (executed / stmtRows.length) * 100,
        };
        if (source) {
          const byLine = new Map<number, number>();
          for (const s of stmtRows) {
            if (s.lineno <= 0) continue;
            const line = source.bodyLine + s.lineno - 1;
            byLine.set(line, Math.max(byLine.get(line) ?? 0, s.exec));
          }
          lineHits = [...byLine.entries()].sort((a, b) => a[0] - b[0]);
          for (const [line, hits] of lineHits) {
            if (hits === 0) uncovered.push(line);
          }
        }
      }
      const generated = f.schema === "public" && (
        f.name === "_label" ||
        (f.name.endsWith("_label") && f.args.startsWith("rec ")) ||
        f.name.startsWith("compute_validate_") ||
        f.name.startsWith("select_rule_")
      );
      const result: FunctionCoverage = {
        oid: f.oid,
        schema: f.schema,
        name: f.name,
        args: f.args,
        language: f.language,
        kind: f.isTrigger
          ? "trigger"
          : f.prokind === "p"
          ? "procedure"
          : "function",
        securityDefiner: f.prosecdef,
        generated,
        calls,
        execCount,
        called,
        statements: stmts,
        branchesPct: branches.get(f.oid) ?? null,
        source,
        lineHits,
        uncoveredLines: uncovered,
      };
      const lineError = lineErrors.get(f.oid);
      if (lineError) result.lineDetailError = lineError;
      return result;
    });

    const tableCoverage: TableCoverage[] = tables.map((t) => {
      const b = this.before.tables.get(t.oid) ??
        { seq: 0, idx: 0, ins: 0, upd: 0, del: 0 };
      const a = after.tables.get(t.oid) ?? b;
      const seqScan = a.seq - b.seq;
      const idxScan = a.idx - b.idx;
      const inserts = a.ins - b.ins;
      const updates = a.upd - b.upd;
      const deletes = a.del - b.del;
      return {
        oid: t.oid,
        schema: t.schema,
        name: t.name,
        policies: t.policies,
        touched: seqScan + idxScan + inserts + updates + deletes > 0,
        seqScan,
        idxScan,
        inserts,
        updates,
        deletes,
      };
    });

    const measurable = functions.filter((f) => f.called !== null);
    const calledCount = measurable.filter((f) => f.called).length;
    const stmtTotal = functions.reduce(
      (s, f) => s + (f.statements?.total ?? 0),
      0,
    );
    const stmtExecuted = functions.reduce(
      (s, f) => s + (f.statements?.executed ?? 0),
      0,
    );
    const touched = tableCoverage.filter((t) => t.touched).length;
    const functionPct = pct(calledCount, measurable.length);

    return {
      version: 1,
      generatedAt: new Date().toISOString(),
      database: maskUrl(databaseUrl),
      capabilities: this.caps,
      run,
      totals: {
        functions: {
          total: functions.length,
          measurable: measurable.length,
          called: calledCount,
          pct: functionPct,
          neverCalled: measurable.length - calledCount,
          unmeasurable: functions.length - measurable.length,
          generated: functions.filter((f) => f.generated).length,
        },
        statements: this.caps.plpgsqlCheck.available && stmtTotal > 0
          ? {
            total: stmtTotal,
            executed: stmtExecuted,
            pct: (stmtExecuted / stmtTotal) * 100,
          }
          : null,
        tables: {
          total: tableCoverage.length,
          touched,
          pct: pct(touched, tableCoverage.length),
        },
      },
      threshold: {
        min: this.opts.min,
        metric: "functions",
        passed: this.opts.min === undefined
          ? null
          : functionPct !== null && functionPct >= this.opts.min,
      },
      functions,
      tables: tableCoverage,
    };
  }
}

