function signature(f: FunctionCoverage): string {
  return `${f.schema}.${f.name}(${f.args})`;
}

function tags(f: FunctionCoverage): string {
  const t: string[] = [];
  if (f.language !== "plpgsql") t.push(f.language);
  if (f.kind === "trigger") t.push("trigger");
  if (f.securityDefiner) t.push("definer");
  if (f.generated) t.push("generated");
  return t.length > 0 ? ` [${t.join(", ")}]` : "";
}

function sourceRef(f: FunctionCoverage): string {
  return f.source ? ` - ${f.source.file}:${f.source.headerLine}` : "";
}

export function renderUncoveredMarkdown(s: CoverageSummary): string {
  const out: string[] = [];
  const c = s.capabilities;
  out.push("# Test coverage: uncovered code");
  out.push("");
  out.push(`Generated: ${s.generatedAt}`);
  out.push(`Database: ${s.database}`);
  out.push(
    `Universe: ${
      c.universe.mode === "extension"
        ? `extension ${c.universe.extension}`
        : `schemas ${c.universe.schemas?.join(", ")}`
    } (${s.totals.functions.total} functions, ${s.totals.tables.total} tables)`,
  );
  out.push(
    `Capabilities: ${
      c.plpgsqlCheck.available
        ? `plpgsql_check ${c.plpgsqlCheck.version} in schema ${c.plpgsqlCheck.schema}`
        : `plpgsql_check unavailable (${c.plpgsqlCheck.reason ?? "unknown"})`
    }; track_functions ${c.trackFunctions.enabled ? "on" : "off"}${
      c.trackFunctions.reason ? ` (${c.trackFunctions.reason})` : ""
    }`,
  );
  out.push(
    `Run: ${s.run.files} files, tests ${
      s.run.testsPassed ? "passed" : "FAILED"
    }${
      s.run.partial
        ? ` (partial:${s.run.filter ? ` filter ${s.run.filter}` : ""}${
          s.run.stoppedEarly ? " stopped early" : ""
        })`
        : ""
    }`,
  );
  out.push("");
  out.push("## Totals");
  out.push("");
  const tf = s.totals.functions;
  out.push(
    `- Functions: ${tf.called}/${tf.measurable} called (${
      fmtPct(tf.pct)
    }); never called ${tf.neverCalled}, not measurable ${tf.unmeasurable}, generated ${tf.generated}`,
  );
  if (s.totals.statements) {
    const ts = s.totals.statements;
    out.push(
      `- PL/pgSQL statements: ${ts.executed}/${ts.total} executed (${
        fmtPct(ts.pct)
      })`,
    );
  } else {
    out.push("- PL/pgSQL statements: not measured");
  }
  out.push(
    `- Tables: ${s.totals.tables.touched}/${s.totals.tables.total} touched (${
      fmtPct(s.totals.tables.pct)
    })`,
  );
  if (s.threshold.min !== undefined) {
    out.push(
      `- Threshold: functions ${fmtPct(tf.pct)} ${
        s.threshold.passed ? ">=" : "<"
      } ${s.threshold.min}% (${s.threshold.passed ? "PASS" : "FAIL"})`,
    );
  }

  const never = s.functions.filter((f) => f.called === false);
  out.push("");
  out.push(`## Functions never called (${never.length})`);
  for (const schema of [...new Set(never.map((f) => f.schema))].sort()) {
    out.push("");
    out.push(`### ${schema}`);
    out.push("");
    for (const f of never.filter((f) => f.schema === schema)) {
      out.push(`- ${f.name}(${f.args})${tags(f)}${sourceRef(f)}`);
    }
  }

  const partial = s.functions
    .filter((f) => f.called && f.statements && f.statements.pct < 100)
    .sort((a, b) => a.statements!.pct - b.statements!.pct);
  out.push("");
  out.push(
    `## Partially covered PL/pgSQL functions (${partial.length}, sorted by statement coverage)`,
  );
  out.push("");
  for (const f of partial) {
    const st = f.statements!;
    const branch = f.branchesPct !== null
      ? `, branches ${fmtPct(f.branchesPct)}`
      : "";
    const lines = f.uncoveredLines.length > 0
      ? `; uncovered lines ${compressRanges(f.uncoveredLines)}`
      : f.source
      ? ""
      : "; source not mapped";
    out.push(
      `- ${signature(f)}${tags(f)}: ${st.executed}/${st.total} statements (${
        fmtPct(st.pct)
      })${branch}${sourceRef(f)}${lines}`,
    );
  }

  const errors = s.functions.filter((f) => f.lineDetailError);
  if (errors.length > 0) {
    out.push("");
    out.push(`## Statement detail unavailable (${errors.length})`);
    out.push("");
    for (const f of errors) {
      out.push(`- ${signature(f)}: ${f.lineDetailError}`);
    }
  }

  const untouched = s.tables.filter((t) => !t.touched);
  out.push("");
  out.push(`## Tables never touched (${untouched.length})`);
  out.push("");
  for (const t of untouched) {
    out.push(`- ${t.schema}.${t.name} (${t.policies} policies)`);
  }

  const unmeasurable = s.functions.filter((f) => f.called === null);
  if (unmeasurable.length > 0) {
    out.push("");
    out.push(`## Not measurable on this connection (${unmeasurable.length})`);
    out.push("");
    for (const f of unmeasurable) {
      out.push(`- ${signature(f)}${tags(f)}${sourceRef(f)}`);
    }
  }

  out.push("");
  out.push("## How to read this");
  out.push("");
  out.push(
    "- A function counts as called when pg_stat_user_functions saw a call or the plpgsql_check profiler executed it during this run.",
  );
  out.push(
    "- SQL-language functions that the planner inlines are never counted by pg_stat_user_functions; check the test files before treating one as untested.",
  );
  out.push(
    "- Never-called PL/pgSQL functions are reported with 0 executed statements even though plpgsql_coverage_statements() would report 100% for them.",
  );
  out.push(
    "- Statement coverage counts profiler statements; a line with several statements is covered when any of them ran.",
  );
  out.push("");
  return out.join("\n");
}

export function renderLcov(s: CoverageSummary): string {
  const byFile = new Map<string, FunctionCoverage[]>();
  for (const f of s.functions) {
    if (!f.source) continue;
    const list = byFile.get(f.source.file) ?? [];
    list.push(f);
    byFile.set(f.source.file, list);
  }
  const out: string[] = [];
  for (const file of [...byFile.keys()].sort()) {
    const fns = byFile.get(file)!;
    out.push("TN:");
    out.push(`SF:${file}`);
    let fnHit = 0;
    for (const f of fns) {
      const name = signature(f).replace(/,/g, ";");
      out.push(`FN:${f.source!.headerLine},${name}`);
      if (f.called === null) continue;
      const hits = Math.max(f.calls ?? 0, f.execCount ?? 0);
      out.push(`FNDA:${hits},${name}`);
      if (hits > 0) fnHit++;
    }
    out.push(`FNF:${fns.length}`);
    out.push(`FNH:${fnHit}`);
    const lines = new Map<number, number>();
    for (const f of fns) {
      for (const [line, hits] of f.lineHits ?? []) {
        lines.set(line, Math.max(lines.get(line) ?? 0, hits));
      }
    }
    let lh = 0;
    for (const line of [...lines.keys()].sort((a, b) => a - b)) {
      const hits = lines.get(line)!;
      out.push(`DA:${line},${hits}`);
      if (hits > 0) lh++;
    }
    out.push(`LF:${lines.size}`);
    out.push(`LH:${lh}`);
    out.push("end_of_record");
  }
  return out.join("\n") + (out.length > 0 ? "\n" : "");
}

/** Writes summary.json, uncovered.md and lcov.info; returns the paths written. */
export async function writeCoverageReports(
  summary: CoverageSummary,
  outDir: string,
): Promise<string[]> {
  await Deno.mkdir(outDir, { recursive: true });
  const files: [string, string][] = [
    [`${outDir}/summary.json`, JSON.stringify(summary, null, 2) + "\n"],
    [`${outDir}/uncovered.md`, renderUncoveredMarkdown(summary)],
    [`${outDir}/lcov.info`, renderLcov(summary)],
  ];
  for (const [path, content] of files) {
    await Deno.writeTextFile(path, content);
  }
  return files.map(([path]) => path);
}

export function printCoverageSummary(
  s: CoverageSummary,
  tap: boolean,
  reportPaths: string[],
): void {
  const p = tap ? "# " : "";
  const tf = s.totals.functions;
  const lines: string[] = [];
  lines.push("");
  lines.push(
    `  Coverage (plpgsql_check profiler + pg_stat_user_functions)${
      s.run.partial ? " - partial run" : ""
    }`,
  );
  lines.push(
    `    Functions:  ${tf.called}/${tf.measurable} called (${
      fmtPct(tf.pct)
    })   ${tf.neverCalled} never called, ${tf.unmeasurable} not measurable, ${tf.generated} generated`,
  );
  if (s.totals.statements) {
    const ts = s.totals.statements;
    lines.push(
      `    Statements: ${ts.executed}/${ts.total} executed (${fmtPct(ts.pct)})`,
    );
  } else {
    lines.push(`    Statements: not measured (plpgsql_check unavailable)`);
  }
  lines.push(
    `    Tables:     ${s.totals.tables.touched}/${s.totals.tables.total} touched (${
      fmtPct(s.totals.tables.pct)
    })`,
  );
  if (reportPaths.length > 0) {
    lines.push(`    Reports:    ${reportPaths.join(", ")}`);
  }
  if (s.threshold.min !== undefined) {
    lines.push(
      `    Threshold:  functions ${fmtPct(tf.pct)} ${
        s.threshold.passed ? ">=" : "<"
      } ${s.threshold.min}% (${s.threshold.passed ? "PASS" : "FAIL"})`,
    );
  }
  for (const line of lines) {
    console.log(line === "" ? (tap ? "#" : "") : `${p}${line}`);
  }
}

/** True unless a threshold was requested and not met (or not measurable). */
export function coverageGatePassed(s: CoverageSummary): boolean {
  return s.threshold.passed !== false;
}
