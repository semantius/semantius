const CORE_SCHEMAS = ["public", "common", "rbac", "audit", "pgmq"];
const TEST_HELPERS = ["authenticate_as", "extract_api_key_id"];

/** Decode deno-postgres numerics (int8 arrives as bigint, float8 as number). */
function num(v: unknown): number {
  if (typeof v === "bigint") return Number(v);
  if (typeof v === "number") return v;
  if (typeof v === "string") return Number(v);
  return 0;
}

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function maskUrl(url: string): string {
  return url.replace(/\/\/[^@]+@/, "//***:***@");
}

function pct(part: number, whole: number): number | null {
  return whole > 0 ? (part / whole) * 100 : null;
}

function fmtPct(value: number | null): string {
  return value === null ? "n/a" : `${value.toFixed(1)}%`;
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/** Compress sorted line numbers into "12-15, 20, 31-33". */
function compressRanges(lines: number[]): string {
  if (lines.length === 0) return "";
  const parts: string[] = [];
  let start = lines[0];
  let prev = lines[0];
  for (let i = 1; i <= lines.length; i++) {
    const cur = lines[i];
    if (cur === prev + 1) {
      prev = cur;
      continue;
    }
    parts.push(start === prev ? `${start}` : `${start}-${prev}`);
    start = cur;
    prev = cur;
  }
  return parts.join(", ");
}

function chunks<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) {
    out.push(items.slice(i, i + size));
  }
  return out;
}

// ---------------------------------------------------------------------------
// Source mapping: pg_proc.prosrc -> apps/<app>/migrations/<file>.sql:<line>
// ---------------------------------------------------------------------------

interface SourceHeader {
  index: number;
  line: number;
  schema?: string;
  name: string;
}

interface SourceFile {
  path: string;
  text: string;
  lineStarts: number[];
  headers: SourceHeader[];
}

interface SourceLocation {
  file: string;
  headerLine: number;
  bodyLine: number;
}

/** 1-based line number of a character offset. */
function lineAt(lineStarts: number[], index: number): number {
  let lo = 0;
  let hi = lineStarts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (lineStarts[mid] <= index) lo = mid;
    else hi = mid - 1;
  }
  return lo + 1;
}

/**
 * Loads every migration file in migrate order (apps/_core first, then the other
 * apps sorted by name; apps/test is skipped because it only holds pgtap). The
 * function bodies are stored verbatim by both install channels (migrate sends
 * the file as-is, the extension generator only rewrites CREATE EXTENSION lines),
 * so prosrc is byte-identical to the dollar-quoted text in the file.
 */
async function buildSourceIndex(): Promise<SourceFile[]> {
  const apps: string[] = [];
  try {
    for await (const entry of Deno.readDir("./apps")) {
      if (
        entry.isDirectory && entry.name !== "_core" && entry.name !== "test"
      ) {
        apps.push(entry.name);
      }
    }
  } catch {
    return [];
  }
  apps.sort();

  const files: SourceFile[] = [];
  for (const app of ["_core", ...apps]) {
    const dir = `./apps/${app}/migrations`;
    const names: string[] = [];
    try {
      for await (const entry of Deno.readDir(dir)) {
        if (entry.isFile && entry.name.endsWith(".sql")) names.push(entry.name);
      }
    } catch {
      continue;
    }
    names.sort();
    for (const name of names) {
      const raw = await Deno.readTextFile(`${dir}/${name}`);
      const text = raw.replace(/\r\n?/g, "\n");
      const lineStarts = [0];
      for (let i = 0; i < text.length; i++) {
        if (text.charCodeAt(i) === 10) lineStarts.push(i + 1);
      }
      const headers: SourceHeader[] = [];
      const re =
        /CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+(?:"?([A-Za-z_][A-Za-z0-9_]*)"?\.)?"?([A-Za-z_][A-Za-z0-9_]*)"?/gi;
      let m: RegExpExecArray | null;
      while ((m = re.exec(text)) !== null) {
        headers.push({
          index: m.index,
          line: lineAt(lineStarts, m.index),
          schema: m[1]?.toLowerCase(),
          name: m[2].toLowerCase(),
        });
      }
      files.push({
        path: `apps/${app}/migrations/${name}`,
        text,
        lineStarts,
        headers,
      });
    }
  }
  return files;
}

/**
 * Finds the migration line where a function body is defined. The body text
 * alone is ambiguous (dozens of trigger functions share "BEGIN RETURN NEW; END"),
 * so a match only counts when the nearest preceding CREATE FUNCTION header
 * names the same function. The last match in migrate order wins, which is the
 * definition that is live in the database.
 */
function locateFunction(
  index: SourceFile[],
  fn: { schema: string; name: string; prosrc: string },
): SourceLocation | null {
  const body = fn.prosrc.replace(/\r\n?/g, "\n");
  if (body.trim() === "") return null;
  const name = fn.name.toLowerCase();
  const schema = fn.schema.toLowerCase();
  let best: SourceLocation | null = null;

  for (const file of index) {
    let from = 0;
    let i: number;
    while ((i = file.text.indexOf(body, from)) !== -1) {
      from = i + 1;
      let header: SourceHeader | undefined;
      for (const h of file.headers) {
        if (h.index < i) header = h;
        else break;
      }
      if (!header || header.name !== name) continue;
      if (header.schema && header.schema !== schema) continue;
      best = {
        file: file.path,
        headerLine: header.line,
        bodyLine: lineAt(file.lineStarts, i),
      };
    }
  }
  return best;
}

