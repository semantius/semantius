/**
 * testgen_jsonlogic command
 * Generates the pgTAP files of the two shared JsonLogic case lists, which the
 * Semantius app runs against its own evaluator and checker as well:
 *
 *   0100_test_jsonlogic.json -> 0100_test_jsonlogic.sql
 *     Each array entry [rule, data, result] produces a pgTAP is() assertion
 *     that evaluate_json_logic(rule, data) returns result.
 *
 *   0115_test_jsonlogic_check.json -> 0115_test_jsonlogic_check.sql
 *     Each array entry [rule, null] says that the save accepts the rule, and
 *     [rule, code, path] that jl_rule_problem(rule) finds its first mistake
 *     under that code at that JSON pointer.
 *
 * String entries become SQL comments in both.
 */

import { join } from "@std/path";
import { resolveAppDir } from "../assets.ts";
import { RUNNING_UNDER_DENO } from "../invocation.ts";

interface CaseList {
  json: string;
  sql: string;
  /** The entry's shape as the warning names it. */
  shape: string;
  /** The word each assertion's description starts with. */
  label: string;
  /** The assertion for one entry, or undefined when the entry is malformed. */
  assertion(entry: unknown[], label: string): string[] | undefined;
}

function sqlEscape(s: string): string {
  return s.replace(/'/g, "''");
}

function toJsonbLiteral(value: unknown): string {
  return `'${sqlEscape(JSON.stringify(value))}'::jsonb`;
}

const CASE_LISTS: CaseList[] = [
  {
    json: "0100_test_jsonlogic.json",
    sql: "0100_test_jsonlogic.sql",
    shape: "[rule, data, result]",
    label: "test",
    assertion(entry, label) {
      if (entry.length < 3) return undefined;
      const [rule, data, result] = entry;
      return [
        `SELECT is(`,
        `    evaluate_json_logic(${toJsonbLiteral(rule)}, ${toJsonbLiteral(data)}),`,
        `    ${toJsonbLiteral(result)},`,
        `    '${label}'`,
        `);`,
      ];
    },
  },
  {
    json: "0115_test_jsonlogic_check.json",
    sql: "0115_test_jsonlogic_check.sql",
    shape: "[rule, null] or [rule, code, path]",
    label: "check",
    assertion(entry, label) {
      const [rule, code, path] = entry;
      const accepted = entry.length === 2 && code === null;
      const refused = entry.length === 3 && typeof code === "string" &&
        typeof path === "string";
      if (!accepted && !refused) return undefined;
      const expected = accepted ? "NULL::jsonb" : toJsonbLiteral([code, path]);
      return [
        `SELECT is(`,
        `    (SELECT jsonb_build_array(p ->> 'code', p ->> 'path')`,
        `       FROM jl_rule_problem(${toJsonbLiteral(rule)}) AS p WHERE p IS NOT NULL),`,
        `    ${expected},`,
        `    '${label}'`,
        `);`,
      ];
    },
  },
];

async function generate(dir: string, list: CaseList, source: string): Promise<void> {
  const jsonInputPath = join(dir, list.json);
  const sqlOutputPath = join(dir, list.sql);

  console.log(`Reading ${jsonInputPath}...`);

  let entries: unknown[];
  try {
    const content = await Deno.readTextFile(jsonInputPath);
    const parsed = JSON.parse(content);
    if (!Array.isArray(parsed)) {
      console.error(`Expected ${jsonInputPath} to contain a JSON array`);
      Deno.exit(1);
    }
    entries = parsed;
  } catch (error) {
    console.error(
      `Failed to read ${jsonInputPath}:`,
      error instanceof Error ? error.message : String(error),
    );
    Deno.exit(1);
  }

  const body: string[] = [];
  let testNum = 0;

  for (const entry of entries) {
    if (typeof entry === "string") {
      body.push(`-- ${entry}`);
    } else if (Array.isArray(entry)) {
      const assertion = list.assertion(entry, `${list.label} ${testNum + 1}`);
      if (!assertion) {
        console.warn(
          `Skipping malformed entry (expected ${list.shape}): ${JSON.stringify(entry)}`,
        );
        continue;
      }
      testNum++;
      body.push(...assertion);
    }
  }

  const lines = [
    "-- Generated by testgen_jsonlogic command",
    `-- DO NOT EDIT - modify ${list.json} and run deno task testgen_jsonlogic`,
    "BEGIN;",
    "",
    `SELECT plan(${testNum});`,
    "",
    ...body,
    "",
    "SELECT * FROM finish();",
    "ROLLBACK;",
  ];

  try {
    await Deno.writeTextFile(sqlOutputPath, lines.join("\n"));
  } catch (error) {
    // The only writable copy of apps/test is one on disk. Inside the compiled
    // binary it is read-only by construction, and this command regenerates a
    // file that is committed to the repository anyway - so the answer is
    // always "run it from a checkout", never "try somewhere else".
    //
    // The source label alone is not the test: a checkout collapses its two
    // identical roots to one entry called "embedded", so keying on that would
    // tell someone who IS in a checkout to go find one. Only a compiled binary
    // has a read-only apps/.
    if (!RUNNING_UNDER_DENO && source === "embedded") {
      console.error(
        `Cannot write ${sqlOutputPath}: the copy of apps/test that ships with ` +
          `the CLI is read-only. Run this from a checkout of the repository, ` +
          `where apps/test/tests/ is a real directory.`,
      );
      Deno.exit(1);
    }
    throw error;
  }
  console.log(`Generated ${sqlOutputPath} with ${testNum} tests.`);
}

export async function testgenJsonlogicCommand(): Promise<void> {
  const testApp = await resolveAppDir("test");
  if (!testApp) {
    console.error("apps/test was not found, so there is nothing to generate.");
    Deno.exit(1);
  }
  for (const list of CASE_LISTS) {
    await generate(join(testApp.dir, "tests"), list, testApp.source);
  }
}
